# -*- coding: utf-8 -*-

"""
表情符号配置文件
用于定义AI输出文本中的表情占位符到颜文字（kaomoji）的映射关系。

LLM 输出的表情写法存在多种变体（尖括号 <微笑>、半角冒号 :微笑:、
全角冒号 ：微笑： 等），本配置对每个表情生成覆盖全部变体的正则，
统一替换为颜文字——不依赖 Discord 自定义表情（服务器无需上传表情包）。
同一表情可配置多个颜文字，发送时随机选择。
"""

import re

# 匹配单个表情的全部书写变体：<名> / :名: / ：名： 及混搭（如 ：名>）
def _kaomoji_pattern(name: str) -> re.Pattern:
    return re.compile(rf"[<：:]{name}[>：:]")

